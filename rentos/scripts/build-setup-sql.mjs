// Concatenates every migration, in order, into supabase/setup.sql so the whole
// schema can be pasted into the Supabase SQL Editor in one go (no CLI/login).
// Re-run after adding a migration: npm run db:bundle
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase/migrations");

const files = (await readdir(dir)).filter((f) => f.endsWith(".sql")).sort();
let out = `-- RentOS: full schema, all migrations in order. GENERATED by
-- scripts/build-setup-sql.mjs -- edit the files in supabase/migrations/ instead.
-- Paste into Supabase Dashboard -> SQL Editor -> New query -> Run.
-- Run it ONCE on an empty project; re-running will error on "already exists".
`;
for (const file of files) {
  out += `\n-- ===== ${file} =====\n${await readFile(path.join(dir, file), "utf8")}\n`;
}
await writeFile(path.join(root, "supabase/setup.sql"), out);
console.log(`wrote supabase/setup.sql (${files.length} migrations)`);
